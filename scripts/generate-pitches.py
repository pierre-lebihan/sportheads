"""Generate Rust/browser geometry from the Flash reference and public symmetry corrections."""
from pathlib import Path
import json
import math
captured = json.loads(Path('tests/fixtures/pitches/original.json').read_text())
balanced = json.loads(Path('data/balanced-pitches.json').read_text())
assert [pitch['frame'] for pitch in captured['pitches']] == list(range(2, 21))

def number(value):
    if value == math.pi / 2:
        return 'std::f64::consts::FRAC_PI_2'
    return repr(float(value))

lines = [
    '//! Historical Flash geometry and symmetric public variants.',
    '//! Regenerate: python3 scripts/generate-pitches.py',
    '//! Sources: tests/fixtures/pitches/original.json and data/balanced-pitches.json.',
    'use crate::{body::Body, math::Vec2, world::World};',
    '',
    'enum Obstacle {',
    '    Circle(f64, f64, f64),',
    '    Box(f64, f64, f64, f64, f64),',
    '}',
    '',
    'const PITCHES: [&[Obstacle]; 19] = [',
]
original = {}
for pitch in captured['pitches']:
    original[str(pitch['frame'])] = []
    lines.append(f"    // Blueprint frame {pitch['frame']} (two-player selection {pitch['frame'] - 1}).")
    lines.append('    &[')
    for body in pitch['obstacles']:
        shape = body['shapes'][0]
        assert shape['density'] == 0 and shape['friction'] == .5 and shape['restitution'] == 0 and shape['group'] == 0
        if shape['type'] == 0:
            values = [body['x'], body['y'], shape['radius']]
            variant = 'Circle'
        else:
            vertices = shape['vertices']
            hx, hy = vertices[2]
            assert vertices == [[-hx, -hy], [hx, -hy], [hx, hy], [-hx, hy]]
            values = [body['x'], body['y'], hx, hy, body['angle']]
            variant = 'Box'
        lines.append(f"        Obstacle::{variant}({', '.join(map(number, values))}),")
        original[str(pitch['frame'])].append([variant.lower(), *values])
    lines.append('    ],')
lines.extend([
    '];',
    '',
    '/// Append props after the seventeen base match bodies, as onRender does.',
    '/// The original two-player selector exposes blueprint frames 2 through 20.',
    'pub fn spawn(world: &mut World, pitch: u32) {',
    '    let Some(props) = pitch.checked_sub(2).and_then(|i| PITCHES.get(i as usize)) else { return; };',
    '    spawn_props(world, props);',
    '}',
    '',
    '/// Symmetric public variants; historical Flash geometry stays available via spawn.',
    'pub fn spawn_balanced(world: &mut World, pitch: u32) {',
    '    let props: &[Obstacle] = match pitch {',
])
for pitch, props in balanced.items():
    lines.append(f'        {pitch} => &[')
    for kind, *values in props:
        variant = {'circle': 'Circle', 'box': 'Box'}[kind]
        assert len(values) == (3 if kind == 'circle' else 5)
        lines.append(f"            Obstacle::{variant}({', '.join(map(number, values))}),")
    lines.append('        ],')
lines.extend([
    '        _ => { spawn(world, pitch); return; }',
    '    };',
    '    spawn_props(world, props);',
    '}',
    '',
    'fn spawn_props(world: &mut World, props: &[Obstacle]) {',
    '    for prop in props {',
    '        match *prop {',
    '            Obstacle::Circle(x, y, radius) => {',
    '                world.add_body(Body::circle(Vec2::new(x, y), radius, 0.0, 0.5, 0.0, false));',
    '            }',
    '            Obstacle::Box(x, y, hx, hy, angle) => {',
    '                let position = Vec2::new(x, y);',
    '                let i = world.add_body(Body::rectangle(position, hx, hy, 0.0, 0.5, 0.0, false));',
    '                world.set_transform(i, position, angle);',
    '            }',
    '        }',
    '    }',
    '}',
])
Path('src/pitches.rs').write_text('\n'.join(lines) + '\n')
Path('web/pitch-geometry.js').write_text('// Generated by scripts/generate-pitches.py from the captured Flash geometry and symmetry corrections.\n'
    + 'export const ORIGINAL_PITCHES = ' + json.dumps(original, indent=2) + ';\n'
    + 'export const BALANCED_PITCHES = ' + json.dumps(balanced, indent=2) + ';\n')
print('Generated Rust and browser geometry: 19 historical pitches, 9 symmetric corrections')
